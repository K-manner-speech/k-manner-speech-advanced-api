-- "학교 식당 위치 묻기" 의 opening_message 가 시나리오의 성공 조건을 스스로
-- 방해하고 있었다.
--
--   기존: "어, 안녕! 오랜만이네. 어디 가는 길이야?"
--
-- 페르소나가 먼저 질문을 던지면 사용자는 답변자가 된다. "어디 가?" 에 답하느라
-- 인사를 건너뛰어 polite_greeting 이 미달되고, "식당 가요" 라고 답하면 페르소나가
-- 위치를 먼저 알려줘 clear_question 을 연습할 기회 자체가 사라진다.
--
-- 인사만 건네고 대화의 주도권을 사용자에게 남긴다.

update public.scenarios
set opening_message = '어? 오랜만이네. 반갑다!',
    updated_at = now()
where id = '20000000-0000-4000-8000-000000000003';

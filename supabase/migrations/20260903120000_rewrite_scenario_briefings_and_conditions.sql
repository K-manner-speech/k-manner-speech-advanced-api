           '팀장님께 이번 주 금요일로 미뤄도 될지 요청해 보자.'
where id = '20000000-0000-4000-8000-000000000001';

update public.scenarios
set goal = '당신은 고객센터 상담원이다. 고객이 주문한 상품이 예정일보다 3일 늦게 도착해 '
           '불만을 제기했다. 안내할 수 있는 방안은 배송비 전액 환급, 다음 구매 10% 할인 쿠폰, '
           '반품·환불 접수 세 가지다. 불편에 공감하며 응대하고, 방안을 안내해 고객의 수긍을 얻어내자.'
where id = '20000000-0000-4000-8000-000000000002';

-- ---------------------------------------------------------------------------
-- 2) 기존 조건을 충분 조건으로 강등
-- ---------------------------------------------------------------------------

update public.scenario_success_conditions
set is_required = false,
    sort_order = sort_order + 10
where condition_key in (
  'polite_greeting', 'clear_question', 'gratitude',
  'polite_request', 'reason_given',
  'empathy', 'resolution'
);


-- 시나리오를 "상황 브리핑 + 결과 하나" 구조로 다시 세운다.
--
-- 기존 goal 은 채점표처럼 쓰여 있어서 사용자가 읽고 상황에 몰입할 문장이
-- 아니었다. "상대방을 배려하며 일정 변경을 요청한다" 는 무엇을·언제로·왜
-- 바꾸자는 건지 하나도 알려주지 않아, 사용자가 설정을 통째로 지어내야 했다.
-- goal 을 상황 서술로 바꾼다. 채점은 success_conditions 가 담당하므로 goal 이
-- 채점표 문체일 필요가 없고, 페르소나도 상황을 알아야 자연스럽게 연기한다.
--
-- 필수 조건은 "상대에게서 무언가를 받아냈는가" 하나로 줄인다. 인사·존댓말은
-- turn_feedback 의 honorifics·courtesy 로 이미 채점되므로, 필수로 또 막으면
-- 같은 것을 두 번 벌주는 셈이다. 조기 종료를 막지 않되 판정과 기록은 계속
-- 되도록 is_required 만 내린다. 기존 조건은 삭제하지 않는다. 진행 기록이
-- FK 로 물려 있고, 충분 조건으로 남겨야 피드백에서 "여기까지 했으면 더
-- 좋았다" 를 말할 수 있다.

